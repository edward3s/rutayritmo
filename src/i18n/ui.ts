export type UIKey = keyof typeof UI.es;

export function t(lang: Lang, key: UIKey): string {
  return UI[lang][key];
}

export function difficultyLabel(lang: Lang, value: string): string {
  const map: Record<string, UIKey> = {
    Fácil: 'difficultyEasy',
    Moderada: 'difficultyModerate',
    Exigente: 'difficultyDemanding',
  };
  const key = map[value];
  return key ? t(lang, key) : value;
}
